import { jsPDF } from "jspdf";
import type {
  MixtureClassificationOutput,
  MixtureIngredient,
  ClassificationResult,
  PhysicalForm,
} from "./classification/types";
import { H_CODE_DESCRIPTIONS } from "./classification/types";

const MARGIN = 15;
const PAGE_WIDTH = 210;
const CONTENT_WIDTH = PAGE_WIDTH - MARGIN * 2;
const LINE_HEIGHT = 5;
const FONT_SIZE = {
  title: 16,
  subtitle: 12,
  heading: 10,
  body: 8,
  small: 7,
};

const FORM_LABELS: Record<PhysicalForm, string> = {
  liquid: "Liquid",
  solid: "Solid / Powder",
  gas: "Gas",
  aerosol: "Aerosol",
};

function addPageFooter(doc: jsPDF, pageNum: number, totalPages: number) {
  const y = 285;
  doc.setFontSize(FONT_SIZE.small);
  doc.setTextColor(150);
  doc.text(
    "Generated by CHRA Classifier | Based on ICOP 2014 & 2019 Amendment | For guidance only",
    MARGIN,
    y,
  );
  doc.text(`Page ${pageNum} of ${totalPages}`, PAGE_WIDTH - MARGIN, y, {
    align: "right",
  });
  doc.setTextColor(0);
}

function checkPageBreak(doc: jsPDF, y: number, needed: number): number {
  if (y + needed > 275) {
    doc.addPage();
    return MARGIN + 10;
  }
  return y;
}

function drawCell(
  doc: jsPDF,
  x: number,
  y: number,
  w: number,
  h: number,
  text: string,
  options?: { fill?: string; bold?: boolean; align?: "left" | "center"; fontSize?: number },
) {
  if (options?.fill) {
    const [r, g, b] = hexToRgb(options.fill);
    doc.setFillColor(r, g, b);
    doc.rect(x, y, w, h, "F");
  }
  doc.setDrawColor(200);
  doc.rect(x, y, w, h, "S");

  doc.setFontSize(options?.fontSize ?? FONT_SIZE.small);
  doc.setFont("helvetica", options?.bold ? "bold" : "normal");
  const align = options?.align ?? "left";
  const textX = align === "center" ? x + w / 2 : x + 2;

  const lines = doc.splitTextToSize(text, w - 4);
  const textY = y + h / 2 - ((lines.length - 1) * (FONT_SIZE.small * 0.35)) / 2 + 2;
  for (let i = 0; i < lines.length; i++) {
    doc.text(lines[i], textX, textY + i * (FONT_SIZE.small * 0.45), {
      align,
    });
  }
}

function hexToRgb(hex: string): [number, number, number] {
  const result = /^#?([a-f\d]{2})([a-f\d]{2})([a-f\d]{2})$/i.exec(hex);
  if (!result) return [255, 255, 255];
  return [parseInt(result[1], 16), parseInt(result[2], 16), parseInt(result[3], 16)];
}

export function generateClassificationPDF(output: MixtureClassificationOutput): jsPDF {
  const doc = new jsPDF("p", "mm", "a4");
  let y = MARGIN;

  // Title
  doc.setFontSize(FONT_SIZE.title);
  doc.setFont("helvetica", "bold");
  doc.text("Chemical Hazard Classification Report", MARGIN, y + 8);
  y += 14;

  doc.setFontSize(FONT_SIZE.body);
  doc.setFont("helvetica", "normal");
  doc.setTextColor(100);
  doc.text(`Generated: ${new Date().toLocaleString()}`, MARGIN, y);
  doc.text(`Physical Form: ${FORM_LABELS[output.physicalForm]}`, MARGIN + 90, y);
  doc.setTextColor(0);
  y += 4;

  doc.setDrawColor(41, 98, 255);
  doc.setLineWidth(0.5);
  doc.line(MARGIN, y, PAGE_WIDTH - MARGIN, y);
  y += 8;

  // Section 1: Ingredient Summary
  y = renderIngredientTable(doc, y, output.ingredients);
  y += 6;

  // Section 2: Classification Results Summary
  y = checkPageBreak(doc, y, 30);
  y = renderResultsSummary(doc, y, output);
  y += 6;

  // Section 3: Hazard Comparison Matrix
  if (output.ingredients.length >= 1) {
    y = checkPageBreak(doc, y, 40);
    y = renderHazardMatrix(doc, y, output);
    y += 6;
  }

  // Section 4: Step-by-Step Proofs
  y = checkPageBreak(doc, y, 20);
  y = renderProofs(doc, y, output.results);
  y += 6;

  // Warnings
  if (output.warnings.length > 0) {
    y = checkPageBreak(doc, y, 20);
    y = renderWarnings(doc, y, output.warnings);
    y += 6;
  }

  // Disclaimer
  y = checkPageBreak(doc, y, 25);
  renderDisclaimer(doc, y);

  // Page numbers
  const totalPages = doc.getNumberOfPages();
  for (let i = 1; i <= totalPages; i++) {
    doc.setPage(i);
    addPageFooter(doc, i, totalPages);
  }

  return doc;
}

function renderIngredientTable(doc: jsPDF, y: number, ingredients: MixtureIngredient[]): number {
  doc.setFontSize(FONT_SIZE.heading);
  doc.setFont("helvetica", "bold");
  doc.text("1. Mixture Composition", MARGIN, y);
  y += 6;

  const cols = [
    { label: "No.", width: 10 },
    { label: "Chemical Name", width: 50 },
    { label: "CAS No.", width: 25 },
    { label: "Conc. (%)", width: 20 },
    { label: "Classifications", width: CONTENT_WIDTH - 105 },
  ];

  const rowH = 8;

  // Header
  let x = MARGIN;
  for (const col of cols) {
    drawCell(doc, x, y, col.width, rowH, col.label, {
      fill: "#2962ff",
      bold: true,
      align: "center",
    });
    doc.setTextColor(255);
    // redraw text in white
    doc.setFontSize(FONT_SIZE.small);
    doc.setFont("helvetica", "bold");
    const lines = doc.splitTextToSize(col.label, col.width - 4);
    const textY = y + rowH / 2 + 1.5;
    for (let li = 0; li < lines.length; li++) {
      doc.text(lines[li], x + col.width / 2, textY + li * 3, { align: "center" });
    }
    doc.setTextColor(0);
    x += col.width;
  }
  y += rowH;

  // Rows
  for (let i = 0; i < ingredients.length; i++) {
    const ing = ingredients[i];
    const clsText = ing.chemical.classifications
      .map((c) => `${c.code} (${c.hCode})`)
      .join(", ");
    const rowLines = Math.max(1, Math.ceil(clsText.length / 40));
    const rh = Math.max(rowH, rowLines * 4 + 4);

    y = checkPageBreak(doc, y, rh);
    x = MARGIN;
    const fill = i % 2 === 0 ? "#f8f9fa" : "#ffffff";

    drawCell(doc, x, y, cols[0].width, rh, String(i + 1), { fill, align: "center" });
    x += cols[0].width;
    drawCell(doc, x, y, cols[1].width, rh, ing.chemical.name, { fill });
    x += cols[1].width;
    drawCell(doc, x, y, cols[2].width, rh, ing.chemical.cas || "-", { fill, align: "center" });
    x += cols[2].width;
    drawCell(doc, x, y, cols[3].width, rh, ing.concentration.toFixed(1), { fill, align: "center" });
    x += cols[3].width;
    drawCell(doc, x, y, cols[4].width, rh, clsText || "None", { fill, fontSize: 6 });

    y += rh;
  }

  const total = ingredients.reduce((s, i) => s + i.concentration, 0);
  doc.setFontSize(FONT_SIZE.body);
  doc.setFont("helvetica", "bold");
  doc.text(`Total Concentration: ${total.toFixed(1)}%`, MARGIN, y + 5);
  y += 7;

  return y;
}

function renderResultsSummary(doc: jsPDF, y: number, output: MixtureClassificationOutput): number {
  doc.setFontSize(FONT_SIZE.heading);
  doc.setFont("helvetica", "bold");
  doc.text("2. Classification Results", MARGIN, y);
  y += 6;

  if (output.results.length === 0) {
    doc.setFontSize(FONT_SIZE.body);
    doc.setFont("helvetica", "normal");
    doc.text("Not classified - mixture does not meet criteria for any hazard classification.", MARGIN, y);
    return y + 5;
  }

  // Signal word
  const highestSignal = output.results.some((r) => r.signalWord === "Danger")
    ? "Danger"
    : output.results.some((r) => r.signalWord === "Warning")
      ? "Warning"
      : "None";

  doc.setFontSize(FONT_SIZE.body);
  doc.setFont("helvetica", "normal");
  doc.text(`Signal Word: `, MARGIN, y);
  doc.setFont("helvetica", "bold");
  doc.setTextColor(highestSignal === "Danger" ? 220 : 200, highestSignal === "Danger" ? 38 : 150, highestSignal === "Danger" ? 38 : 0);
  doc.text(highestSignal, MARGIN + 25, y);
  doc.setTextColor(0);
  y += 5;

  // Results table
  const cols = [
    { label: "Hazard Class", width: 55 },
    { label: "Category", width: 25 },
    { label: "H-Code", width: 15 },
    { label: "Hazard Statement", width: 60 },
    { label: "Signal", width: CONTENT_WIDTH - 155 },
  ];

  const rowH = 7;
  let x = MARGIN;
  for (const col of cols) {
    drawCell(doc, x, y, col.width, rowH, col.label, { fill: "#e3f2fd", bold: true, align: "center" });
    x += col.width;
  }
  y += rowH;

  for (let i = 0; i < output.results.length; i++) {
    y = checkPageBreak(doc, y, rowH);
    const r = output.results[i];
    x = MARGIN;
    const fill = i % 2 === 0 ? "#ffffff" : "#f8f9fa";

    drawCell(doc, x, y, cols[0].width, rowH, r.hazardClass, { fill });
    x += cols[0].width;
    drawCell(doc, x, y, cols[1].width, rowH, r.category, { fill, align: "center" });
    x += cols[1].width;
    drawCell(doc, x, y, cols[2].width, rowH, r.hCode, { fill, align: "center" });
    x += cols[2].width;
    drawCell(doc, x, y, cols[3].width, rowH, H_CODE_DESCRIPTIONS[r.hCode] || r.hCode, { fill, fontSize: 6 });
    x += cols[3].width;
    drawCell(doc, x, y, cols[4].width, rowH, r.signalWord || "-", { fill, align: "center" });
    y += rowH;
  }

  return y;
}

function renderHazardMatrix(doc: jsPDF, y: number, output: MixtureClassificationOutput): number {
  doc.setFontSize(FONT_SIZE.heading);
  doc.setFont("helvetica", "bold");
  doc.text("3. Ingredient Hazard Comparison", MARGIN, y);
  y += 6;

  const ingredients = output.ingredients;
  const nameWidth = 45;
  const chemCount = Math.min(ingredients.length, 8);
  const availWidth = CONTENT_WIDTH - nameWidth;
  const chemColWidth = Math.min(availWidth / chemCount, 25);

  // Collect all unique hazard classes from all ingredients
  const allHazardCodes = new Set<string>();
  for (const ing of ingredients) {
    for (const cls of ing.chemical.classifications) {
      allHazardCodes.add(cls.hCode);
    }
  }

  const hazardCodes = Array.from(allHazardCodes).sort();
  if (hazardCodes.length === 0) {
    doc.setFontSize(FONT_SIZE.body);
    doc.setFont("helvetica", "normal");
    doc.text("No hazard classifications found for any ingredient.", MARGIN, y);
    return y + 5;
  }

  const rowH = 7;

  // Header row
  let x = MARGIN;
  drawCell(doc, x, y, nameWidth, rowH * 2, "H-Code", { fill: "#2962ff", bold: true, align: "center" });
  // redraw header text in white
  doc.setTextColor(255);
  doc.setFontSize(FONT_SIZE.small);
  doc.setFont("helvetica", "bold");
  doc.text("H-Code", x + nameWidth / 2, y + rowH + 1, { align: "center" });
  doc.setTextColor(0);

  x += nameWidth;
  for (let i = 0; i < chemCount; i++) {
    const name = ingredients[i].chemical.name;
    const shortName = name.length > 12 ? name.substring(0, 11) + "..." : name;
    drawCell(doc, x, y, chemColWidth, rowH, shortName, { fill: "#2962ff", bold: true, align: "center", fontSize: 6 });
    // redraw in white
    doc.setTextColor(255);
    doc.setFontSize(6);
    doc.setFont("helvetica", "bold");
    const lines = doc.splitTextToSize(shortName, chemColWidth - 2);
    doc.text(lines[0], x + chemColWidth / 2, y + 4, { align: "center" });
    doc.setTextColor(0);

    drawCell(doc, x, y + rowH, chemColWidth, rowH, `${ingredients[i].concentration}%`, { fill: "#e3f2fd", align: "center", fontSize: 6 });
    x += chemColWidth;
  }
  y += rowH * 2;

  // Hazard rows
  for (let hi = 0; hi < hazardCodes.length; hi++) {
    y = checkPageBreak(doc, y, rowH);
    const hCode = hazardCodes[hi];
    const fill = hi % 2 === 0 ? "#ffffff" : "#f5f5f5";
    x = MARGIN;

    const description = H_CODE_DESCRIPTIONS[hCode] || hCode;
    const cellText = `${hCode} - ${description.length > 30 ? description.substring(0, 29) + "..." : description}`;
    drawCell(doc, x, y, nameWidth, rowH, cellText, { fill, fontSize: 6 });
    x += nameWidth;

    for (let i = 0; i < chemCount; i++) {
      const cls = ingredients[i].chemical.classifications.find((c) => c.hCode === hCode);
      const cellVal = cls ? cls.code : "—";
      const cellFill = cls ? "#e8f5e9" : fill;
      drawCell(doc, x, y, chemColWidth, rowH, cellVal, { fill: cellFill, align: "center", fontSize: 5 });
      x += chemColWidth;
    }
    y += rowH;
  }

  return y;
}

function renderProofs(doc: jsPDF, y: number, results: ClassificationResult[]): number {
  doc.setFontSize(FONT_SIZE.heading);
  doc.setFont("helvetica", "bold");
  doc.text("4. Classification Proofs", MARGIN, y);
  y += 6;

  for (const r of results) {
    y = checkPageBreak(doc, y, 25);

    // Proof header
    doc.setFillColor(235, 245, 255);
    doc.rect(MARGIN, y, CONTENT_WIDTH, 7, "F");
    doc.setDrawColor(41, 98, 255);
    doc.line(MARGIN, y, MARGIN, y + 7);
    doc.line(MARGIN, y + 7, MARGIN + CONTENT_WIDTH, y + 7);
    doc.setDrawColor(200);

    doc.setFontSize(FONT_SIZE.body);
    doc.setFont("helvetica", "bold");
    doc.text(`${r.hazardClass} — ${r.category} (${r.hCode})`, MARGIN + 3, y + 4.5);
    y += 9;

    doc.setFontSize(FONT_SIZE.small);
    doc.setFont("helvetica", "normal");
    doc.setTextColor(100);
    doc.text(`Method: ${r.proof.method}`, MARGIN + 2, y);
    doc.setTextColor(0);
    y += 4;

    if (r.proof.formula) {
      doc.setFont("helvetica", "italic");
      doc.setFontSize(FONT_SIZE.small);
      doc.text(`Formula: ${stripTableRefs(r.proof.formula)}`, MARGIN + 2, y);
      doc.setFont("helvetica", "normal");
      y += 4;
    }

    // Steps
    for (let si = 0; si < r.proof.steps.length; si++) {
      const step = r.proof.steps[si];
      const stepLines = [];
      stepLines.push(`${si + 1}. ${stripTableRefs(step.description)}`);
      if (step.calculation) stepLines.push(`   ${stripTableRefs(step.calculation)}`);
      if (step.result) stepLines.push(`   => ${stripTableRefs(step.result)}`);

      const neededHeight = stepLines.length * LINE_HEIGHT;
      y = checkPageBreak(doc, y, neededHeight);

      for (const line of stepLines) {
        doc.setFontSize(FONT_SIZE.small);
        if (line.startsWith("   =>")) {
          doc.setFont("helvetica", "bold");
          doc.setTextColor(0, 128, 0);
        } else if (line.startsWith("   ")) {
          doc.setFont("courier", "normal");
          doc.setTextColor(30, 80, 180);
        } else {
          doc.setFont("helvetica", "normal");
          doc.setTextColor(0);
        }
        const wrapped = doc.splitTextToSize(line, CONTENT_WIDTH - 4);
        for (const wl of wrapped) {
          doc.text(wl, MARGIN + 2, y);
          y += 3.5;
        }
      }
      y += 1;
    }

    // Conclusion
    y = checkPageBreak(doc, y, 10);
    doc.setFillColor(232, 245, 233);
    doc.rect(MARGIN, y, CONTENT_WIDTH, 6, "F");
    doc.setFontSize(FONT_SIZE.small);
    doc.setFont("helvetica", "bold");
    doc.setTextColor(27, 94, 32);
    doc.text(stripTableRefs(r.proof.conclusion), MARGIN + 3, y + 4);
    doc.setTextColor(0);
    y += 8;

    doc.setFont("helvetica", "normal");
    doc.setFontSize(6);
    doc.setTextColor(100);
    doc.text(`Reference: ${stripTableRefs(r.proof.reference)}`, MARGIN + 2, y);
    doc.setTextColor(0);
    y += 6;
  }

  return y;
}

function renderWarnings(doc: jsPDF, y: number, warnings: string[]): number {
  doc.setFontSize(FONT_SIZE.heading);
  doc.setFont("helvetica", "bold");
  doc.text("Warnings", MARGIN, y);
  y += 5;

  doc.setFontSize(FONT_SIZE.small);
  doc.setFont("helvetica", "normal");
  for (const w of warnings) {
    y = checkPageBreak(doc, y, 5);
    doc.text(`• ${w}`, MARGIN + 2, y);
    y += 4;
  }

  return y;
}

function renderDisclaimer(doc: jsPDF, y: number) {
  doc.setFillColor(245, 245, 245);
  doc.rect(MARGIN, y, CONTENT_WIDTH, 20, "F");
  doc.setDrawColor(200);
  doc.rect(MARGIN, y, CONTENT_WIDTH, 20, "S");

  doc.setFontSize(6);
  doc.setFont("helvetica", "bold");
  doc.text("Disclaimer", MARGIN + 3, y + 4);
  doc.setFont("helvetica", "normal");
  doc.setTextColor(80);
  const disclaimerText =
    "This classification is generated based on the ICOP on Classification, Labelling and Safety Data Sheet " +
    "of Hazardous Chemicals 2014 (and 2019 Amendment). It is intended as guidance only and should not be " +
    "considered a substitute for professional assessment. Always verify results against official Safety " +
    "Data Sheets (SDS) and consult qualified professionals for regulatory compliance.";
  const lines = doc.splitTextToSize(disclaimerText, CONTENT_WIDTH - 6);
  for (let i = 0; i < lines.length; i++) {
    doc.text(lines[i], MARGIN + 3, y + 7 + i * 2.5);
  }
  doc.setTextColor(0);
}

function stripTableRefs(text: string): string {
  return text.replace(/Table \d+\.\d+/g, (match) => match);
}
